func CalcClassQuestExp(level, completionCount int) int64 {
	if level < 0 || level > 160 {
		level = 0
	}
	idx := completionCount % 10
	return int64(math.Round(float64(BasicGetExp[level]) * ClassQuestMoneyExpNum[idx] * 10 / 31.5))
}

func CalcClassQuestMoney(level, completionCount int) int64 {
	if level < 0 || level > 160 {
		level = 0
	}
	idx := completionCount % 10
	return int64(math.Round(float64(BasicGetMoney[level]) * ClassQuestMoneyExpNum[idx] * 3 / 31.5))
}

func CallboardMultiplier(color int) float64 {
	if color < 0 || color > 4 {
		return 1
	}
	return CallboardAwardNum[color]
}
