func playerLevelCumulativeExp(level int) int64 {
	if level <= 1 {
		return 0
	}

	index := level - 1
	if index < 0 {
		return 0
	}
	if index >= len(playerLevelExpCumulative) {
		return playerLevelExpCumulative[len(playerLevelExpCumulative)-1]
	}

	return playerLevelExpCumulative[index]
}

